package co.learn;

public class TypeDataBoolean {
    public static void main(String[] args) {
        // Type Data Boolean
        boolean thisTrue = true; // --> this value is true
        boolean thisFalse = false; // --> this value is false

        System.out.println("\n======== TYPE DATA BOOLEAN =======");
        System.out.println(thisTrue);
        System.out.println(thisFalse);
        System.out.println("\n");

        int number = 20;

        int number2 = 20;

        if (number == number2) {
            System.out.println(thisTrue);
        } else {
            System.out.println(thisFalse);
        }
    }

}
