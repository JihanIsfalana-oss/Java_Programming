package co.learn;

import java.lang.String; // --> This can be Imported for Using String

public class TypeDataString {
    public static void main(String[] args) {
        // Type Data String
        String name; // This Named by Declaration Variable
        name = "Mochammad Jihan Isfalana"; // --> This Named by Assignment

        // Print Out to the Terminal
        System.out.println(name);

        // Manipulate String
        name = "Uzumaki Naruto";

        // Print Out to the Terminal
        System.out.println(name);

        // keywords Helper built-in
        // tab
        System.out.println("Name\t\t: " + name);

        // newline
        System.out.println("\nName : " + name);
    }

}
