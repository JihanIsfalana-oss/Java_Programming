package co.lessons;

public class OperationComparisons {
    public static void main(String[] args) {
        // Comparations

        int A = 10;
        int B = 8;

        // Compare
        System.out.println(A < B);
        System.out.println(A > B);
        System.out.println(A <= B);
        System.out.println(A >= B);
        System.out.println(A != B);
        System.out.println(A == B);

        /* The Value will return just 2 value that are true or false like Boolean type data values */
    }

}
